def desenhar_mapa(grupo_colisao):
    for i_linha,linha in enumerate(MAP):
        for coluna,obj in enumerate(linha):
            if obj != 0:
                pos = (coluna*TILE_SIZE,i_linha*TILE_SIZE)
                bloco = tiles[obj](pos)
                grupo_colisao.add(bloco)
                
